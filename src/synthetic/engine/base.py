"""The pluggable model interface (PRD §9 "build vs. buy").

A *tabular model* learns from a sample table and produces new rows that look
like it. The relational orchestrator does not care which model it is: it only
calls :meth:`TabularModel.sample`. That lets us swap the Gaussian copula used
today for a deep generative model later without touching the rest of the code.

Models must:

* draw all randomness from the ``numpy.random.Generator`` they are given
  (never from global state), so output is reproducible (FR10);
* never store raw source rows (store aggregates such as quantiles instead);
* only cover the columns they were asked to model; keys and PII columns are
  generated by the spec generators.
"""

from __future__ import annotations

from abc import ABC, abstractmethod

import numpy as np
import pandas as pd

from synthetic.schema import Column


class TabularModel(ABC):
    """Base class for single-table models."""

    #: Short identifier stored in job metadata, e.g. ``"gaussian_copula"``.
    name: str = "base"

    @abstractmethod
    def fit(self, data: pd.DataFrame, columns: list[Column], rng: np.random.Generator) -> TabularModel:
        """Learn from ``data`` restricted to ``columns``. Returns ``self``."""

    @abstractmethod
    def sample(self, n: int, rng: np.random.Generator) -> pd.DataFrame:
        """Return ``n`` new rows for the modeled columns."""

    @property
    @abstractmethod
    def columns(self) -> list[str]:
        """Names of the columns this model produces."""


#: Registry of available models. Add new engines here.
MODEL_REGISTRY: dict[str, type[TabularModel]] = {}


def register_model(cls: type[TabularModel]) -> type[TabularModel]:
    """Class decorator that makes a model selectable by name."""
    MODEL_REGISTRY[cls.name] = cls
    return cls
